const { app, BrowserWindow } = require('electron')
const fs = require('node:fs')
const assert = require('node:assert/strict')

app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, webPreferences: { offscreen: true, nodeIntegration: true, contextIsolation: false, backgroundThrottling: false } })
  try {
    await win.loadURL('data:text/html,<html><body><div id="root"></div></body></html>')
    await win.webContents.executeJavaScript(fs.readFileSync(process.argv[2], 'utf8'))
    const js = (source) => win.webContents.executeJavaScript(source)
    const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms))
    const input = async (selector, value) => {
      await js('var el=document.querySelector(' + JSON.stringify(selector) + ');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,"value").set.call(el,' + JSON.stringify(value) + ');el.dispatchEvent(new Event("input",{bubbles:true}))')
      await wait(60)
    }
    await wait(150)
    await input('.ex-simple-trade-card input', '100')
    await js('document.querySelector(".ex-simple-trade-card input").dispatchEvent(new KeyboardEvent("keydown",{key:"Enter",bubbles:true}))')
    await wait(160)
    assert.equal(await js('fixture.posts()'), 1)
    assert.match(await js('document.querySelector(".ex-simple-big-action-btn").textContent'), /[0-9]+%/)
    assert.equal(await js('fixture.cash()'), 1000)
    await js('fixture.complete()')
    await wait(30)
    assert.match(await js('document.querySelector(".ex-simple-big-action-btn").textContent'), /100%/)
    assert.equal(await js('fixture.cash()'), 1000)
    await wait(150)
    assert.equal(await js('fixture.cash()'), 900)
    await js('fixture.setMode("pro")')
    await wait(120)
    await input('#ex-price-input', '10')
    await input('#ex-qty-input', '10')
    await wait(350)
    await js('document.querySelector(".ex-trade-body > .ex-primary").click()')
    await wait(160)
    assert.equal(await js('fixture.posts()'), 2)
    assert.match(await js('document.querySelector(".ex-trade-body > .ex-primary").textContent'), /[0-9]+%/)
    assert.equal(await js('fixture.cash()'), 900)
    await js('fixture.reject()')
    await wait(100)
    assert.doesNotMatch(await js('document.querySelector(".ex-trade-body > .ex-primary").textContent'), /100%/)
    assert.equal(await js('fixture.cash()'), 900)
    await js('document.querySelectorAll(".ex-trade-mode-seg button")[1].click()')
    await js('Array.from(document.querySelectorAll(".ex-lev-pill")).find(e=>e.textContent.includes("90x")).click()')
    await input('#ex-qty-input', '500')
    await wait(350)
    await js('document.querySelector(".ex-trade-body > .ex-primary").click()')
    await wait(80)
    assert.equal(await js('Boolean(document.querySelector(".ex-modal"))'), true)
    await js('document.querySelector(".ex-modal-actions .ex-primary").click()')
    await wait(80)
    assert.equal(await js('fixture.lastQty()'), 7)
    await js('fixture.accept()')
    await wait(200)
    assert.equal(await js('fixture.cash()'), 800)
    await js('fixture.setMode("bot")')
    await wait(120)
    assert.match(await js('document.querySelector(".ex-strategy-events").textContent'), /已成交/)
    assert.doesNotMatch(await js('document.querySelector(".ex-bot-panel").textContent'), /预估年化/)
    await js('document.querySelector(".ex-bot-action-btn.is-pause").click()')
    await wait(80)
    assert.equal(await js('fixture.strategyWrites()'), 1)
    assert.equal(await js('Boolean(document.querySelector(".ex-bot-action-btn.is-resume"))'), true)
    await js('document.querySelector(".ex-bot-action-btn.is-stop").click()')
    await wait(60)
    await js('document.querySelector(".ex-bot-action-btn.is-stop").click()')
    await wait(120)
    assert.equal(await js('fixture.strategyWrites()'), 2)
    assert.equal(await js('document.querySelectorAll(".ex-bot-card").length'), 0)
    console.log('PASS 策略真实记录、暂停与终止、90倍确认与服务器股数、简单键盘、专业鼠标、百分比与账户时序、拒单不满格')
  } catch (error) {
    console.error(error)
    process.exitCode = 1
  } finally {
    win.destroy()
    app.exit(process.exitCode || 0)
  }
})
