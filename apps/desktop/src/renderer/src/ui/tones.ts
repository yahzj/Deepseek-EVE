export function toneOfAny(key: string | undefined): string {
  if (!key) return 'rgb(var(--wui-dim))'
  return TONES[key] ?? ICO_TONES[key] ?? NAV_TONES[key] ?? 'rgb(var(--wui-dim))'
}

