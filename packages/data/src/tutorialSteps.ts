/** 一教程步骤（步骤号与 core `onboarding.ts` 的 ONB_* 常量一一对应） */
export interface TutorialStepDef {
  /** 步骤号（1..7；与 `ONB_MINE`..`ONB_DIVIDE` 同值） */
  step: number
  /** 步骤标题（通讯主题后缀与顶部引导条共用） */
  title: string
  /** 一句话目标（顶部引导条显示；比正文更短） */
  goal: string
  /** 步骤全文（通讯正文逐段；体例 = 船长 2026-09-11 定的【区块】标题 + 逐行陈述，与序章简报同风格） */
  lines: readonly string[]
  /** 跳转目标页 */
  page: CommsJumpPage
  /** 星图页内标签（仅 page = 'map' 时） */
  mapTab?: string
  /**
   * 任务中心页内标签（仅 page = 'map' + mapTab = 'task' 时；键 = `important`/`resource`/`courier`/`bounty`）。
   * 2026-09-11 船长报告「步骤 2/7 跳转任务中心时不切到指定标签页」：任务中心的内层标签会记住玩家上次的选择，
   * 光切到星图「任务中心」标签不够——交付要在「重要任务」里办，故跳转必须把它一并带上。
   */
  taskTab?: string
  /** 舰船页内标签（仅 page = 'ship' 时） */
  shipTab?: string
  /** 跳转按钮文字 */
  goLabel: string
}

