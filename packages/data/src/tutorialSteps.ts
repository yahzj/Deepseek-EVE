/** 一教程步骤（步骤号与 core `onboarding.ts` 的 ONB_* 常量一一对应） */
export interface TutorialStepDef {
  /** 步骤号（1..7；与 `ONB_MINE`..`ONB_DIVIDE` 同值） */
  step: number
  /** 步骤标题（通讯主题后缀与顶部引导条共用） */
  title: string
  /** 一句话目标（顶部引导条显示；比正文更短） */
  goal: string
  /** 步骤全文（通讯正文逐段；= 原右下角引导卡的完整说明） */
  lines: readonly string[]
  /** 跳转目标页 */
  page: CommsJumpPage
  /** 星图页内标签（仅 page = 'map' 时） */
  mapTab?: string
  /** 舰船页内标签（仅 page = 'ship' 时） */
  shipTab?: string
  /** 跳转按钮文字 */
  goLabel: string
}

