export function itemRarityTierOf(itemId: string): number | undefined {
  const direct = RARITY_TIER[itemId]
  if (direct !== undefined) return direct
  const ship = /^sh-(.+)$/.exec(itemId)
  if (ship) return RARITY_TIER[ship[1]!]
  return undefined
}
